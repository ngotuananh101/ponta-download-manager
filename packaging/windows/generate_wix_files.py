#!/usr/bin/env python3
"""Generate packaging/windows/Files.wxs from a Windows Release bundle.

WiX has no wildcard include, so the release workflow runs this script
before `wix build`: it walks the bundle directory
(apps/desktop/build/windows/x64/runner/Release) and emits one Component per file,
with Directory elements mirroring the bundle layout (data/, lib/,
bin/ — the external tools live in bin/).

Component GUIDs are deterministic (uuid5 over the relative path), so a
rebuild of the same tree produces the same component identities and
MajorUpgrade can replace files in place.

Usage:
    python packaging/windows/generate_wix_files.py [--source-dir DIR]
                                                   [--output FILE]
Defaults resolve against the repo root (two levels up from this file).
"""

import argparse
import hashlib
import sys
import uuid
from pathlib import Path
from xml.sax.saxutils import escape

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_SOURCE = Path("apps/desktop/build/windows/x64/runner/Release")
DEFAULT_OUTPUT = Path("packaging/windows/Files.wxs")

# WiX identifiers: letters, digits, _ and . (must start with a letter
# or _), at most 72 characters.
MAX_ID_LEN = 72


def make_id(prefix, rel_path):
    """A stable WiX Id for a relative path, truncated with a hash suffix
    when the sanitised form would be too long."""
    stem = rel_path.replace("/", "_").replace("\\", "_").replace(".", "_")
    stem = "".join(c if c.isalnum() or c in "._" else "_" for c in stem)
    candidate = prefix + stem
    if len(candidate) <= MAX_ID_LEN:
        return candidate
    digest = hashlib.sha1(rel_path.encode("utf-8")).hexdigest()[:16]
    return prefix + digest


def dir_id(rel_dir):
    """Directory Id for a bundle subdirectory ('' means INSTALLFOLDER)."""
    if not rel_dir:
        return "INSTALLFOLDER"
    return make_id("dir_", rel_dir)


def collect(source_dir):
    """Return (directories, files): directories is a sorted list of
    relative subdirectory paths ('' excluded), files is a sorted list
    of (relative path, parent relative dir) tuples.

    Paths are always posix-style ('data/flutter_assets'). The parent
    is derived by splitting on '/', never with pathlib: on Windows
    Path() is a WindowsPath, so Path('data/flutter_assets').parent
    returns 'data\\flutter_assets', which then becomes a second
    directory named after the whole joined path and collides with the
    real nested one (WiX WIX0091 duplicate Directory id)."""
    directories = set()
    files = []
    for path in sorted(source_dir.rglob("*")):
        if path.is_dir():
            rel = path.relative_to(source_dir).as_posix()
            directories.add(rel)
        elif path.is_file():
            rel = path.relative_to(source_dir).as_posix()
            parent = rel.rpartition("/")[0]
            if parent:
                directories.add(parent)
            files.append((rel, parent))
    directories.discard("")
    return sorted(directories), files


def build_tree(directories):
    """Nested dict of the subdirectory tree: {'data': {'flutter_assets': {}}}."""
    root = {}
    for rel in directories:
        node = root
        for part in rel.split("/"):
            node = node.setdefault(part, {})
    return root


def emit_dirs(tree, prefix, indent, lines):
    """Emit each directory exactly once, nested under its parent."""
    for name in sorted(tree):
        sub = "/".join(prefix + [name])
        did = dir_id(sub)
        children = tree[name]
        if children:
            lines.append(
                f'{indent}<Directory Id="{did}"'
                f' Name="{escape(name)}">'
            )
            emit_dirs(children, prefix + [name], indent + "  ", lines)
            lines.append(f"{indent}</Directory>")
        else:
            lines.append(
                f'{indent}<Directory Id="{did}"'
                f' Name="{escape(name)}" />'
            )


def render(source_dir, directories, files):
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- Generated by packaging/windows/generate_wix_files.py"
        " — do not edit by hand. -->",
        '<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">',
        "  <Fragment>",
        '    <DirectoryRef Id="INSTALLFOLDER">',
    ]
    emit_dirs(build_tree(directories), [], "      ", lines)
    lines.append("    </DirectoryRef>")
    lines.append('    <ComponentGroup Id="FilesComponentGroup">')
    for rel, parent in files:
        comp_id = make_id("cmp_", rel)
        file_id = make_id("fil_", rel)
        guid = uuid.uuid5(uuid.NAMESPACE_URL, "pdm://file/" + rel)
        source = "$(var.SourceDir)\\" + rel.replace("/", "\\")
        lines.append(
            f'      <Component Id="{comp_id}" Directory="{dir_id(parent)}"'
            f' Guid="{guid}">'
        )
        lines.append(
            f'        <File Id="{file_id}" Source="{escape(source)}"'
            ' KeyPath="yes" />'
        )
        lines.append("      </Component>")
    lines.append("    </ComponentGroup>")
    lines.append("  </Fragment>")
    lines.append("</Wix>")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source-dir",
        default=str(REPO_ROOT / DEFAULT_SOURCE),
        help="Release bundle directory (default: %(default)s)",
    )
    parser.add_argument(
        "--output",
        default=str(REPO_ROOT / DEFAULT_OUTPUT),
        help="Fragment to write (default: %(default)s)",
    )
    args = parser.parse_args(argv)
    source_dir = Path(args.source_dir)
    if not source_dir.is_dir():
        print(f"error: source dir not found: {source_dir}", file=sys.stderr)
        return 1
    directories, files = collect(source_dir)
    if not files:
        print(f"error: no files under {source_dir}", file=sys.stderr)
        return 1
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        render(source_dir, directories, files), encoding="utf-8"
    )
    print(f"Wrote {output} ({len(files)} files, "
          f"{len(directories)} directories)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
